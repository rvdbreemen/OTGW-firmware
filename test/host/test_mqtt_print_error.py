#!/usr/bin/env python3
"""TASK-1664 host harness: does PrintMQTTError() stop calling a refused publish
"MQTT TCP disconnected" while the client is still connected?

    python test/host/test_mqtt_print_error.py                        # working tree only
    python test/host/test_mqtt_print_error.py --old-rev 29bfe386b^   # OLD vs FIX, with a mutant

PrintMQTTError() and lastMqttDisconnectReason are sliced by anchor from MQTTstuff.ino
and compiled against stubs (see the .cpp). With --old-rev the run passes only when
FIX passes every case, OLD fails P1 and passes the controls, and the mutant fails P1.
Exit code: 0 PASS, 1 FAIL, 2 harness error.
"""
import argparse
import re
import subprocess
import sys

from test_boiler_unsupported_origin import cut
from test_ot_reserved_range import GEN, HERE, find_vcvars
from test_pic_banner_dispatch import read

MQTT = "src/OTGW-firmware/MQTTstuff.ino"
START = r"^static espMqttClientTypes::DisconnectReason lastMqttDisconnectReason"
END = r"^void PrintMQTTError\(\)"
CASES = ["P1", "C1", "C2"]
DEFECT = ["P1"]
MUTANT = ("if (MQTTclient.connected()) {", "if (false) {")


def export(rev, out_dir, mutate=False):
    out_dir.mkdir(parents=True, exist_ok=True)
    text, first, last = cut(read(MQTT, rev).splitlines(), START, END)
    if mutate:
        if text.count(MUTANT[0]) != 1:
            print(f"MUTANT: pattern must match exactly once, got {text.count(MUTANT[0])}")
            sys.exit(2)
        text = text.replace(*MUTANT)
    origin = f"git {rev}" if rev else "working tree"
    (out_dir / "mqtt_print_error.inc").write_text(
        f"// GENERATED by test_mqtt_print_error.py from the {origin}. Do not edit.\n"
        f"// ---- {MQTT}:{first}-{last} ----\n{text}\n", encoding="utf-8")


def build_and_run(label, out_dir):
    exe = out_dir / "test_mqtt_print_error.exe"
    if exe.exists():
        exe.unlink()
    bat = out_dir / "_compile.bat"
    fwd = str(out_dir).replace("\\", "/")
    bat.write_text("@echo off\r\n"
                   f"call \"{find_vcvars()}\" >nul 2>nul\r\n"
                   f"cl /nologo /EHsc /W3 /std:c++17 /Od /utf-8 /D_CRT_SECURE_NO_WARNINGS "
                   f"/Fo:\"{fwd}/\" /Fe:\"{exe}\" \"{HERE / 'test_mqtt_print_error.cpp'}\" "
                   f"/I\"{out_dir}\"\r\n", encoding="ascii")
    c = subprocess.run(["cmd.exe", "/c", str(bat)], capture_output=True, text=True, errors="replace")
    if c.returncode != 0 or not exe.exists():
        print(c.stdout[-4000:], c.stderr[-2000:])
        print(f"COMPILATION FAILED ({label})")
        sys.exit(2)
    r = subprocess.run([str(exe)], capture_output=True, text=True)
    print(f"== {label} ==")
    print(r.stdout, end="")
    return r.returncode, dict(re.findall(r"^CASE (\S+) (pass|FAIL)\b", r.stdout, re.M))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--old-rev", help="also build OLD from this git revision and run the mutant")
    args = ap.parse_args()

    base = GEN / "mqtt_print_error"
    export(None, base / "fix")
    rc, fix = build_and_run("FIX (working tree)", base / "fix")
    checks = [("FIX passes every case", rc == 0 and sorted(fix) == sorted(CASES)
               and all(v == "pass" for v in fix.values()))]
    if args.old_rev:
        export(args.old_rev, base / "old")
        orc, old = build_and_run(f"OLD (git {args.old_rev})", base / "old")
        checks.append(("OLD fails exactly the defect case P1",
                       sorted(c for c, v in old.items() if v == "FAIL") == DEFECT))
        export(None, base / "mutant", mutate=True)
        _, mut = build_and_run("MUTANT (connected check removed)", base / "mutant")
        checks.append(("MUTANT fails exactly P1",
                       sorted(c for c, v in mut.items() if v == "FAIL") == DEFECT))
    print("== verdict ==")
    for text, ok in checks:
        print(f"  {text}: {'yes' if ok else 'NO'}")
    ok = all(ok for _, ok in checks)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
