#!/usr/bin/env python3
"""TASK-1451 host harness: does MQTT_STATE_INIT keep the last good broker address (per name) and
close the old session when a renamed broker cannot be looked up?

    python test/host/test_mqtt_broker_address.py                       # working tree
    python test/host/test_mqtt_broker_address.py --old-rev origin/dev  # old vs fix

The `case MQTT_STATE_INIT:` block of handleMQTT() is sliced from src/OTGW-firmware/MQTTstuff.ino
(by anchor, never copied) and compiled next to the REAL header mqttBrokerAddress.h; only the DNS shim,
the MQTT client and the debug macros are doubled. With --old-rev both revisions run the same harness: the
run passes only when FIX passes every case and OLD fails exactly the defect cases (H2, H3, H5, H7) while passing
the controls (D1-D6, H1, H4, H6). A source guard also checks the INIT block calls decideMqttBrokerLookup()
and closes/aborts the client (connected() and disconnect(true)), and that it never calls hostByName (tests/test_no_hostbyname.py covers the rest).
Compiler: MSVC (vswhere). Exit: 0 PASS, 1 FAIL, 2 error.
"""
import argparse
import re
import subprocess
import sys

from test_ot_reserved_range import GEN, HERE, find_vcvars
from test_pic_banner_dispatch import read

INO = "src/OTGW-firmware/MQTTstuff.ino"
REPO_SRC = HERE.parent.parent / "src" / "OTGW-firmware"
DEFECT = ["H2", "H3", "H5", "H7"]
CONTROL = ["D1", "D2", "D3", "D4", "D5", "D6", "H1", "H4", "H6"]


def slice_init(text):
    lines = text.splitlines()
    start = [i for i, l in enumerate(lines) if re.match(r"^\s*case MQTT_STATE_INIT:\s*$", l)]
    if len(start) != 1:
        raise SystemExit(f"case MQTT_STATE_INIT: found {len(start)} times")
    end = next((i for i in range(start[0] + 1, len(lines)) if re.match(r"^\s*break;\s*$", lines[i])), None)
    if end is None:
        raise SystemExit("no break; after MQTT_STATE_INIT")
    return "\n".join(lines[start[0] + 1:end]) + "\n"


def export(rev, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    block = slice_init(read(INO, rev))
    origin = f"git {rev}" if rev else "working tree"
    (out_dir / "mqtt_init.inc").write_text(f"// GENERATED by test_mqtt_broker_address.py from {origin}. Do not edit.\n" + block,
                                           encoding="utf-8")
    return block


def build_and_run(label, out_dir):
    exe = out_dir / "test_mqtt_broker_address.exe"
    if exe.exists():
        exe.unlink()
    bat = out_dir / "_compile.bat"
    fwd = str(out_dir).replace("\\", "/")
    bat.write_text("@echo off\r\n"
                   f"call \"{find_vcvars()}\" >nul 2>nul\r\n"
                   f"cl /nologo /EHsc /W3 /std:c++17 /utf-8 /D_CRT_SECURE_NO_WARNINGS "
                   f"/Fo:\"{fwd}/\" /Fe:\"{exe}\" \"{HERE / 'test_mqtt_broker_address.cpp'}\" "
                   f"/I\"{out_dir}\" /I\"{REPO_SRC}\"\r\n", encoding="ascii")
    c = subprocess.run(["cmd.exe", "/c", str(bat)], capture_output=True, text=True, errors="replace")
    if c.returncode != 0 or not exe.exists():
        print(c.stdout[-3000:], c.stderr[-2000:])
        print(f"COMPILATION FAILED ({label})")
        sys.exit(2)
    r = subprocess.run([str(exe)], capture_output=True, text=True, errors="replace")
    print(f"== {label} ==")
    print(r.stdout, end="")
    cases = dict(re.findall(r"^CASE (\S+) (pass|FAIL)\b", r.stdout, re.M))
    return r.returncode, cases


def source_guard(block):
    block = re.sub(r"//[^\n]*", "", block)  # comments may name hostByName
    checks = [
        ("INIT calls decideMqttBrokerLookup()", "decideMqttBrokerLookup(" in block),
        ("INIT resolves with platformResolveHost()", "platformResolveHost(" in block),
        ("INIT never calls hostByName", "hostByName" not in block),
        ("INIT closes the session and aborts a pending CONNECT", "MQTTclient.disconnect(true)" in block and "MQTTclient.connected()" in block),
        ("INIT records the resolved-for name", "MQTTbrokerResolvedFor" in block and "strlcpy(MQTTbrokerResolvedFor" in block),
        ("INIT logs the last-known-address fallback",
         "lookup of [%s] failed, using the last known address %s" in block),
        ("INIT does not resolve straight into MQTTbrokerIP",
         re.search(r"platformResolveHost\([^;]*MQTTbrokerIP\)", block) is None),
    ]
    ok = True
    print("== source guard (working tree) ==")
    for text, good in checks:
        print(f"  {text}: {'yes' if good else 'NO'}")
        ok = ok and good
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--old-rev", help="also build OLD from this git revision and compare")
    args = ap.parse_args()
    fix_dir = GEN / "mqtt_broker_address" / "fix"
    block = export(None, fix_dir)
    guard_ok = source_guard(block)
    fix_rc, fix_cases = build_and_run("FIX (working tree)", fix_dir)
    fix_ok = (fix_rc == 0 and all(v == "pass" for v in fix_cases.values())
              and sorted(fix_cases) == sorted(DEFECT + CONTROL))
    if not args.old_rev:
        ok = fix_ok and guard_ok
        print("RESULT:", "PASS" if ok else "FAIL")
        return 0 if ok else 1
    old_dir = GEN / "mqtt_broker_address" / "old"
    export(args.old_rev, old_dir)
    old_rc, old_cases = build_and_run(f"OLD (git {args.old_rev})", old_dir)
    checks = [
        ("FIX passes every case", fix_ok),
        ("source guard on FIX", guard_ok),
        ("OLD fails every defect case " + ",".join(DEFECT), all(old_cases.get(c) == "FAIL" for c in DEFECT)),
        ("OLD passes the controls " + ",".join(CONTROL), all(old_cases.get(c) == "pass" for c in CONTROL)),
        ("OLD exits 1", old_rc == 1),
    ]
    print("== old-vs-fix verdict ==")
    for text, ok in checks:
        print(f"  {text}: {'yes' if ok else 'NO'}")
    ok = all(ok for _, ok in checks)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
