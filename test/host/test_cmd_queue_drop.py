#!/usr/bin/env python3
"""TASK-1439 host harness: does the PIC command queue report a dropped command
on MQTT and append TP= commands, as 1.x TASK-1431 does?

    python test/host/test_cmd_queue_drop.py                       # working tree
    python test/host/test_cmd_queue_drop.py --old-rev be555235f^  # old vs fix (before TASK-1555's eviction)

The queue is sliced from src/OTGW-firmware/OTGW-Core.ino (from the
"#define OTGW_CMD_RETRY" line through checkCommandResponse()) and PICSection
from src/OTGW-firmware/PICtypes.h, by anchor, never copied. With --old-rev both
revisions are compiled against the same harness: the run passes only when FIX
passes every case and OLD fails exactly the defect cases (R1-R4, refused
commands, TASK-1457) while passing the controls (D1-D4, C1, C2). Compiler: MSVC (vswhere). Exit: 0 PASS, 1 FAIL, 2 error.
"""
import argparse
import re
import subprocess
import sys

from test_ot_reserved_range import GEN, HERE, find_vcvars, slice_by_anchor
from test_pic_banner_dispatch import read, slice_range

CORE = "src/OTGW-firmware/OTGW-Core.ino"
PICTYPES = "src/OTGW-firmware/PICtypes.h"
FW_H = "src/OTGW-firmware/OTGW-firmware.h"
CORE_H = "src/OTGW-firmware/OTGW-Core.h"
# Against a revision before TASK-1439, D1-D4 are the defect cases too; the
# lists below are for the TASK-1457 comparison against a revision with TASK-1439.
# TASK-1555 (compare against a revision with TASK-1457): Q1-Q3 and Q7 are the defect cases, Q4-Q6 controls.
DEFECT = ["Q1", "Q2", "Q3", "Q7"]
CONTROL = ["D1", "D2", "D3", "D4", "C1", "C2", "R1", "R2", "R3", "R4", "Q4", "Q5", "Q6"]


def slice_queue(lines):
    """From '#define OTGW_CMD_RETRY 5' through the closing '}' (column 0) of
    checkCommandResponse(). Brace counting is not used: the function carries a
    commented-out '// } else' line that would end it early."""
    start = [i for i, l in enumerate(lines) if re.match(r"^#define OTGW_CMD_RETRY 5\b", l)]
    fn = [i for i, l in enumerate(lines)
          if re.match(r"^void checkCommandResponse\(const char \*buf, unsigned int len\)", l)]
    if len(start) != 1 or len(fn) != 1 or fn[0] < start[0]:
        raise SystemExit(f"anchors not found once and in order: start={start} fn={fn}")
    end = next((i for i in range(fn[0] + 1, len(lines)) if lines[i].rstrip() == "}"), None)
    if end is None:
        raise SystemExit("no closing brace for checkCommandResponse()")
    return "\n".join(lines[start[0]:end + 1])


def export(rev, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    origin = f"git {rev}" if rev else "working tree"
    head = f"// GENERATED by test_cmd_queue_drop.py from {origin}. Do not edit.\n"
    pic = slice_by_anchor(read(PICTYPES, rev).splitlines(), r"^struct PICSection\b")
    queue = slice_queue(read(CORE, rev).splitlines())
    # What the queue slice declares around itself (the lock guard, the echo-stats type), always read from the
    # working tree: an OLD revision predates them and ignores them.
    core_wt = read(CORE, None).splitlines()
    fw = read(FW_H, None).splitlines()
    coreh = read(CORE_H, None).splitlines()
    support = "\n".join([slice_by_anchor(fw, r"^struct CmdQueueEchoStats\b"),
                         slice_by_anchor(fw, r"^enum class CmdQueueResult\b"),
                         slice_range(coreh, r"^#define PIC_CMD_MAX_LEN\b", r"^struct OT_cmd_t \{"),
                         slice_range(coreh, r"^#define CMDQUEUE_MAX\b", r"^#define CMDQUEUE_MAX\b"),
                         slice_range(core_wt, r"^#define CMD_QUEUE_LOCK_MS\b", r"^#define CMD_QUEUE_LOCK_MS\b"),
                         slice_by_anchor(core_wt, r"^struct CmdQueueLock \{")])
    # The header's default arguments for addCommandToQueue(), in the shape the revision under test defines it
    # (before TASK-1569 it returned void and had no satOwn argument).
    if re.search(r"^CmdQueueResult addCommandToQueue\(", queue, re.M):
        decl = ("CmdQueueResult addCommandToQueue(const char* buf, const int len, const bool forceQueue = false, "
                "const int16_t delay = 1000, const bool satOwn = false);")
    else:
        decl = ("void addCommandToQueue(const char* buf, const int len, const bool forceQueue = false, "
                "const int16_t delay = 1000);")
    (out_dir / "cmdq_decl.inc").write_text(head + decl + "\n", encoding="utf-8")
    (out_dir / "cmdq_support.inc").write_text(head + support + "\n", encoding="utf-8")
    (out_dir / "cmdq_pic_section.inc").write_text(head + pic + "\n", encoding="utf-8")
    (out_dir / "cmdq_queue.inc").write_text(head + queue + "\n", encoding="utf-8")


def build_and_run(label, out_dir):
    exe = out_dir / "test_cmd_queue_drop.exe"
    if exe.exists():
        exe.unlink()
    bat = out_dir / "_compile.bat"
    fwd = str(out_dir).replace("\\", "/")
    bat.write_text("@echo off\r\n"
                   f"call \"{find_vcvars()}\" >nul 2>nul\r\n"
                   f"cl /nologo /EHsc /W3 /std:c++17 /utf-8 /D_CRT_SECURE_NO_WARNINGS "
                   f"/Fo:\"{fwd}/\" /Fe:\"{exe}\" \"{HERE / 'test_cmd_queue_drop.cpp'}\" /I\"{out_dir}\"\r\n",
                   encoding="ascii")
    c = subprocess.run(["cmd.exe", "/c", str(bat)], capture_output=True, text=True, errors="replace")
    if c.returncode != 0 or not exe.exists():
        print(c.stdout[-3000:], c.stderr[-2000:])
        print(f"COMPILATION FAILED ({label})")
        sys.exit(2)
    r = subprocess.run([str(exe)], capture_output=True, text=True, errors="replace")
    print(f"== {label} ==")
    print(r.stdout, end="")
    cases = dict(re.findall(r"^CASE (\S+) (pass|FAIL)\b", r.stdout, re.M))
    return r.returncode, cases


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--old-rev", help="also build OLD from this git revision and compare")
    args = ap.parse_args()
    fix_dir = GEN / "cmd_queue_drop" / "fix"
    export(None, fix_dir)
    fix_rc, fix_cases = build_and_run("FIX (working tree)", fix_dir)
    if not args.old_rev:
        print("RESULT:", "PASS" if fix_rc == 0 else "FAIL")
        return 0 if fix_rc == 0 else 1
    old_dir = GEN / "cmd_queue_drop" / "old"
    export(args.old_rev, old_dir)
    old_rc, old_cases = build_and_run(f"OLD (git {args.old_rev})", old_dir)
    checks = [
        ("FIX passes every case", fix_rc == 0 and all(v == "pass" for v in fix_cases.values())
         and sorted(fix_cases) == sorted(DEFECT + CONTROL)),
        ("OLD fails every defect case " + ",".join(DEFECT), all(old_cases.get(c) == "FAIL" for c in DEFECT)),
        ("OLD passes the controls " + ",".join(CONTROL), all(old_cases.get(c) == "pass" for c in CONTROL)),
        ("OLD exits 1", old_rc == 1),
    ]
    print("== old-vs-fix verdict ==")
    for text, ok in checks:
        print(f"  {text}: {'yes' if ok else 'NO'}")
    ok = all(ok for _, ok in checks)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
