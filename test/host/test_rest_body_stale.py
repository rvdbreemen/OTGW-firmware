#!/usr/bin/env python3
"""TASK-1565 host harness: a request must never read the previous request's body.

    python test/host/test_rest_body_stale.py                    # working tree
    python test/host/test_rest_body_stale.py --old-rev <rev>    # old vs fix

The body-capture code is sliced out of src/OTGW-firmware/webServerCompat.h by
anchor (WebRequestBody .. webCaptureBody incl. webArmDisconnect, hasBodyCompat, bodyCompat, webArmSlotRelease), never copied.
With --old-rev both revisions run against the same harness: the run passes only
when FIX passes every case and OLD fails the defect cases S5, S5b, S6, S7 while passing
the controls S1-S4. Compiler: MSVC (vswhere). Exit: 0 PASS, 1 FAIL, 2 error.
"""
import argparse
import re
import subprocess
import sys

from test_ot_reserved_range import GEN, HERE, find_vcvars, slice_by_anchor
from test_pic_banner_dispatch import read

SRC = "src/OTGW-firmware/webServerCompat.h"
# --old-rev must be d74eb9593 (first fix) or later: S2 is a control there. OLD = HEAD
# is the comparison for the second fix (single onDisconnect slot, webArmDisconnect).
DEFECT = ["S5", "S5b", "S6", "S7"]
CONTROL = ["S1", "S2", "S3", "S4"]


def export(rev, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = read(SRC, rev).splitlines()
    start = next((i for i, l in enumerate(lines) if l.startswith("#ifndef WEB_BODY_MAX_LEN")), None)
    cap = next((i for i, l in enumerate(lines) if l.startswith("inline void webCaptureBody(")), None)
    if start is None or cap is None:
        raise SystemExit("anchors for the body capture not found")
    end = next(i for i in range(cap, len(lines)) if lines[i].rstrip() == "}")
    try:
        arm = slice_by_anchor(lines, r"^inline void webArmSlotRelease\(")
    except SystemExit:
        arm = "inline void webArmSlotRelease() {}"
    parts = ["\n".join(lines[start:end + 1]),
             slice_by_anchor(lines, r"^inline bool hasBodyCompat\("),
             slice_by_anchor(lines, r"^inline const char\* bodyCompat\("),
             arm]
    origin = f"git {rev}" if rev else "working tree"
    # Only old source needs the obsolete disconnect-owned file-slot context.
    if any("g_fileSlotHeld" in part for part in parts):
        parts.insert(0, "static bool g_fileSlotHeld = false;")
    (out_dir / "body_slice.inc").write_text(f"// GENERATED by test_rest_body_stale.py from {origin}. Do not edit.\n"
                                            + "\n".join(parts) + "\n", encoding="utf-8")


def build_and_run(label, out_dir):
    exe = out_dir / "test_rest_body_stale.exe"
    if exe.exists():
        exe.unlink()
    bat = out_dir / "_compile.bat"
    fwd = str(out_dir).replace("\\", "/")
    bat.write_text("@echo off\r\n"
                   f"call \"{find_vcvars()}\" >nul 2>nul\r\n"
                   f"cl /nologo /EHsc /W3 /std:c++17 /utf-8 /D_CRT_SECURE_NO_WARNINGS "
                   f"/Fo:\"{fwd}/\" /Fe:\"{exe}\" \"{HERE / 'test_rest_body_stale.cpp'}\" /I\"{out_dir}\"\r\n",
                   encoding="ascii")
    c = subprocess.run(["cmd.exe", "/c", str(bat)], capture_output=True, text=True, errors="replace")
    if c.returncode != 0 or not exe.exists():
        print(c.stdout[-3000:], c.stderr[-2000:])
        print(f"COMPILATION FAILED ({label})")
        sys.exit(2)
    r = subprocess.run([str(exe)], capture_output=True, text=True, errors="replace")
    print(f"== {label} ==")
    print(r.stdout, end="")
    return r.returncode, dict(re.findall(r"^CASE (\S+) (pass|FAIL)\b", r.stdout, re.M))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--old-rev", help="also build OLD from this git revision and compare")
    args = ap.parse_args()
    fix_dir = GEN / "rest_body_stale" / "fix"
    export(None, fix_dir)
    fix_rc, fix_cases = build_and_run("FIX (working tree)", fix_dir)
    if not args.old_rev:
        ok = fix_rc == 0 and sorted(fix_cases) == sorted(DEFECT + CONTROL)
        print("RESULT:", "PASS" if ok else "FAIL")
        return 0 if ok else 1
    old_dir = GEN / "rest_body_stale" / "old"
    export(args.old_rev, old_dir)
    old_rc, old_cases = build_and_run(f"OLD (git {args.old_rev})", old_dir)
    checks = [
        ("FIX passes every case", fix_rc == 0 and sorted(fix_cases) == sorted(DEFECT + CONTROL)
         and all(v == "pass" for v in fix_cases.values())),
        ("OLD fails the defect case " + ",".join(DEFECT), all(old_cases.get(c) == "FAIL" for c in DEFECT)),
        ("OLD passes the controls " + ",".join(CONTROL), all(old_cases.get(c) == "pass" for c in CONTROL)),
        ("OLD exits 1", old_rc == 1),
    ]
    print("== old-vs-fix verdict ==")
    for text, ok in checks:
        print(f"  {text}: {'yes' if ok else 'NO'}")
    ok = all(ok for _, ok in checks)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
