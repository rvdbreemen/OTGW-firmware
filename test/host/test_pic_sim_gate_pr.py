#!/usr/bin/env python3
"""TASK-1943 / ADR-244 host harness: does a PR= report command reach the PIC while a
simulation is on, while CS= and the other commands stay held back (ADR-117)?

    python test/host/test_pic_sim_gate_pr.py                         # working tree
    python test/host/test_pic_sim_gate_pr.py --old-rev origin/dev    # old vs fix

The simulation gate block of sendPICSerial() (OTGW-Core.ino, ADR-117 path (a)) and
satSimulationBlocksBusTx() (SATcontrol.ino) are sliced by anchor, never copied. With
--old-rev the run passes only when FIX passes every case and OLD fails exactly the
defect cases (D1-D3: PR= held back) while passing the controls.
Compiler: MSVC (vswhere). Exit: 0 PASS, 1 FAIL, 2 error.
"""
import argparse
import re
import subprocess
import sys

from test_ot_reserved_range import GEN, HERE, host_cxx_build, slice_by_anchor
from test_pic_banner_dispatch import read

CORE = "src/OTGW-firmware/OTGW-Core.ino"
SAT = "src/OTGW-firmware/SATcontrol.ino"
DEFECT = ["D1", "D2", "D3"]
CONTROL = ["C1", "C2", "C3", "C4", "C5"]


def export(rev, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    origin = f"git {rev}" if rev else "working tree"
    head = f"// GENERATED by test_pic_sim_gate_pr.py from {origin}. Do not edit.\n"
    gate = slice_by_anchor(read(SAT, rev).splitlines(), r"^bool satSimulationBlocksBusTx\(const char\* cmd,")
    block = slice_by_anchor(read(CORE, rev).splitlines(), r"// TASK-795 \S+ path \(a\): block PIC serial")
    (out_dir / "gate.inc").write_text(head + gate + "\n", encoding="utf-8")
    (out_dir / "block.inc").write_text(head + block + "\n", encoding="utf-8")


def build_and_run(label, out_dir):
    exe = out_dir / "test_pic_sim_gate_pr.exe"
    if exe.exists():
        exe.unlink()
    ok, out_ = host_cxx_build([HERE / 'test_pic_sim_gate_pr.cpp'], exe, includes=[out_dir], workdir=out_dir)
    if not ok:
        print(out_[-3000:])
        print(f"COMPILATION FAILED ({label})")
        sys.exit(2)
    r = subprocess.run([str(exe)], capture_output=True, text=True, errors="replace")
    print(f"== {label} ==")
    print(r.stdout, end="")
    cases = dict(re.findall(r"^CASE (\S+) (pass|FAIL)\b", r.stdout, re.M))
    return r.returncode, cases


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--old-rev", help="also build OLD from this git revision and compare")
    args = ap.parse_args()
    fix_dir = GEN / "pic_sim_gate_pr" / "fix"
    export(None, fix_dir)
    fix_rc, fix_cases = build_and_run("FIX (working tree)", fix_dir)
    if not args.old_rev:
        print("RESULT:", "PASS" if fix_rc == 0 else "FAIL")
        return 0 if fix_rc == 0 else 1
    old_dir = GEN / "pic_sim_gate_pr" / "old"
    export(args.old_rev, old_dir)
    old_rc, old_cases = build_and_run(f"OLD (git {args.old_rev})", old_dir)
    checks = [
        ("FIX passes every case", fix_rc == 0 and all(v == "pass" for v in fix_cases.values())
         and sorted(fix_cases) == sorted(DEFECT + CONTROL)),
        ("OLD fails exactly the defect case " + ",".join(DEFECT),
         all(old_cases.get(c) == "FAIL" for c in DEFECT)),
        ("OLD passes the controls " + ",".join(CONTROL), all(old_cases.get(c) == "pass" for c in CONTROL)),
        ("OLD exits 1", old_rc == 1),
    ]
    print("== old-vs-fix verdict ==")
    for text, ok in checks:
        print(f"  {text}: {'yes' if ok else 'NO'}")
    ok = all(ok for _, ok in checks)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
