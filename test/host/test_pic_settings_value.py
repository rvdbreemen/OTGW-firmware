#!/usr/bin/env python3
"""TASK-1406 host harness: is a non-text PR= answer (PR=Q 0xFF after a PIC
reprogram) stored and published as readable ASCII?

    python test/host/test_pic_settings_value.py                       # working tree
    python test/host/test_pic_settings_value.py --old-rev origin/dev  # old vs fix

handlePRresponse() is sliced from src/OTGW-firmware/OTGW-Core.ino and
PicSettingsSection from src/OTGW-firmware/PICtypes.h, by anchor, never copied,
so the buffer sizes and the store path are the ones of the revision under test.
With --old-rev both revisions are compiled against the same harness: the run
passes only when FIX passes every case and OLD fails exactly the defect case
(D1) while passing the controls (C1, C2, C3).
Compiler: MSVC (vswhere), as the other harnesses. Exit: 0 PASS, 1 FAIL, 2 error.
"""
import argparse
import re
import subprocess
import sys

from test_ot_reserved_range import GEN, HERE, find_vcvars, slice_by_anchor
from test_pic_banner_dispatch import read

CORE = "src/OTGW-firmware/OTGW-Core.ino"
PICTYPES = "src/OTGW-firmware/PICtypes.h"
DEFECT = ["D1"]
CONTROL = ["C1", "C2", "C3"]


def export(rev, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    origin = f"git {rev}" if rev else "working tree"
    head = f"// GENERATED by test_pic_settings_value.py from {origin}. Do not edit.\n"
    struct = slice_by_anchor(read(PICTYPES, rev).splitlines(), r"^struct PicSettingsSection\b")
    handler = slice_by_anchor(read(CORE, rev).splitlines(), r"^static void handlePRresponse\(const char\* buf, size_t len\)")
    (out_dir / "pic_settings_struct.inc").write_text(head + struct + "\n", encoding="utf-8")
    (out_dir / "pic_settings_handler.inc").write_text(head + handler + "\n", encoding="utf-8")


def build_and_run(label, out_dir):
    exe = out_dir / "test_pic_settings_value.exe"
    if exe.exists():
        exe.unlink()
    bat = out_dir / "_compile.bat"
    fwd = str(out_dir).replace("\\", "/")
    bat.write_text("@echo off\r\n"
                   f"call \"{find_vcvars()}\" >nul 2>nul\r\n"
                   f"cl /nologo /EHsc /W3 /std:c++17 /utf-8 /D_CRT_SECURE_NO_WARNINGS "
                   f"/Fo:\"{fwd}/\" /Fe:\"{exe}\" \"{HERE / 'test_pic_settings_value.cpp'}\" /I\"{out_dir}\"\r\n",
                   encoding="ascii")
    c = subprocess.run(["cmd.exe", "/c", str(bat)], capture_output=True, text=True, errors="replace")
    if c.returncode != 0 or not exe.exists():
        print(c.stdout[-3000:], c.stderr[-2000:])
        print(f"COMPILATION FAILED ({label})")
        sys.exit(2)
    r = subprocess.run([str(exe)], capture_output=True, text=True, errors="replace")
    print(f"== {label} ==")
    print(r.stdout, end="")
    cases = dict(re.findall(r"^CASE (\S+) (pass|FAIL)\b", r.stdout, re.M))
    return r.returncode, cases


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--old-rev", help="also build OLD from this git revision and compare")
    args = ap.parse_args()
    fix_dir = GEN / "pic_settings_value" / "fix"
    export(None, fix_dir)
    fix_rc, fix_cases = build_and_run("FIX (working tree)", fix_dir)
    if not args.old_rev:
        print("RESULT:", "PASS" if fix_rc == 0 else "FAIL")
        return 0 if fix_rc == 0 else 1
    old_dir = GEN / "pic_settings_value" / "old"
    export(args.old_rev, old_dir)
    old_rc, old_cases = build_and_run(f"OLD (git {args.old_rev})", old_dir)
    checks = [
        ("FIX passes every case", fix_rc == 0 and all(v == "pass" for v in fix_cases.values())
         and sorted(fix_cases) == sorted(DEFECT + CONTROL)),
        ("OLD fails exactly the defect case " + ",".join(DEFECT),
         all(old_cases.get(c) == "FAIL" for c in DEFECT)),
        ("OLD passes the controls " + ",".join(CONTROL), all(old_cases.get(c) == "pass" for c in CONTROL)),
        ("OLD exits 1", old_rc == 1),
    ]
    print("== old-vs-fix verdict ==")
    for text, ok in checks:
        print(f"  {text}: {'yes' if ok else 'NO'}")
    ok = all(ok for _, ok in checks)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
