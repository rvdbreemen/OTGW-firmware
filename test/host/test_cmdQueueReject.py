#!/usr/bin/env python3
"""TASK-1442 host harness: is a command the PIC refuses (NG, BV, OR, ...)
reported on MQTT instead of being taken as confirmed?

    python test/host/test_cmdQueueReject.py                    # working tree
    python test/host/test_cmdQueueReject.py --old-rev HEAD     # old vs fix

The 1.x command queue is sliced from src/OTGW-firmware/OTGW-Core.ino, from the
'#define OTGW_CMD_RETRY 5' line through the closing brace of
checkOTGWcmdqueue(), never copied. With --old-rev both revisions are compiled
against the same harness: the run passes only when FIX passes every case and
OLD fails exactly the defect cases (R1-R3) while passing the controls (C1-C3).
Compiler: MSVC, located with vswhere. Exit: 0 PASS, 1 FAIL, 2 harness error.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
GEN = HERE / "build" / "cmdq_reject"
CORE = "src/OTGW-firmware/OTGW-Core.ino"
DEFECT = ["R1", "R2", "R3"]
CONTROL = ["C1", "C2", "C3"]


def read(rev):
    if rev is None:
        return (REPO / CORE).read_text(encoding="utf-8", errors="replace")
    return subprocess.run(["git", "-C", str(REPO), "show", f"{rev}:{CORE}"], capture_output=True,
                          text=True, encoding="utf-8", errors="replace", check=True).stdout


def slice_queue(lines):
    """From '#define OTGW_CMD_RETRY 5' through the closing '}' (column 0) of
    checkOTGWcmdqueue(). Brace counting is not used: the function carries a
    commented-out '// } else' line that would end it early."""
    start = [i for i, l in enumerate(lines) if re.match(r"^#define OTGW_CMD_RETRY 5\b", l)]
    fn = [i for i, l in enumerate(lines) if re.match(r"^void checkOTGWcmdqueue\(const char \*buf, unsigned int len\)", l)]
    if len(start) != 1 or len(fn) != 1 or fn[0] < start[0]:
        raise SystemExit(f"anchors not found once and in order: start={start} fn={fn}")
    end = next((i for i in range(fn[0] + 1, len(lines)) if lines[i].rstrip() == "}"), None)
    if end is None:
        raise SystemExit("no closing brace for checkOTGWcmdqueue()")
    return "\n".join(lines[start[0]:end + 1])


def find_vcvars():
    vswhere = Path(r"C:\Program Files (x86)\Microsoft Visual Studio\Installer\vswhere.exe")
    if not vswhere.exists():
        raise SystemExit("vswhere.exe not found: Visual Studio Build Tools required")
    root = subprocess.run([str(vswhere), "-latest", "-products", "*", "-property", "installationPath"],
                          capture_output=True, text=True, check=True).stdout.strip()
    return Path(root) / "VC" / "Auxiliary" / "Build" / "vcvars64.bat"


def build_and_run(label, rev, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    origin = f"git {rev}" if rev else "working tree"
    (out_dir / "cmdq_reject.inc").write_text(
        f"// GENERATED by test_cmdQueueReject.py from {origin}. Do not edit.\n"
        + slice_queue(read(rev).splitlines()) + "\n", encoding="utf-8")
    exe = out_dir / "test_cmdQueueReject.exe"
    if exe.exists():
        exe.unlink()
    bat = out_dir / "_compile.bat"
    fwd = str(out_dir).replace("\\", "/")
    bat.write_text("@echo off\r\n"
                   f"call \"{find_vcvars()}\" >nul 2>nul\r\n"
                   f"cl /nologo /EHsc /W3 /std:c++17 /utf-8 /D_CRT_SECURE_NO_WARNINGS "
                   f"/Fo:\"{fwd}/\" /Fe:\"{exe}\" \"{HERE / 'test_cmdQueueReject.cpp'}\" /I\"{out_dir}\"\r\n",
                   encoding="ascii")
    c = subprocess.run(["cmd.exe", "/c", str(bat)], capture_output=True, text=True, errors="replace")
    if c.returncode != 0 or not exe.exists():
        print(c.stdout[-3000:], c.stderr[-2000:])
        print(f"COMPILATION FAILED ({label})")
        sys.exit(2)
    r = subprocess.run([str(exe)], capture_output=True, text=True, errors="replace")
    print(f"== {label} ==")
    print(r.stdout, end="")
    return r.returncode, dict(re.findall(r"^CASE (\S+) (pass|FAIL)\b", r.stdout, re.M))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--old-rev", help="also build OLD from this git revision and compare")
    args = ap.parse_args()
    fix_rc, fix_cases = build_and_run("FIX (working tree)", None, GEN / "fix")
    if not args.old_rev:
        print("RESULT:", "PASS" if fix_rc == 0 else "FAIL")
        return 0 if fix_rc == 0 else 1
    old_rc, old_cases = build_and_run(f"OLD (git {args.old_rev})", args.old_rev, GEN / "old")
    checks = [
        ("FIX passes every case", fix_rc == 0 and all(v == "pass" for v in fix_cases.values())
         and sorted(fix_cases) == sorted(DEFECT + CONTROL)),
        ("OLD fails every defect case " + ",".join(DEFECT), all(old_cases.get(c) == "FAIL" for c in DEFECT)),
        ("OLD passes the controls " + ",".join(CONTROL), all(old_cases.get(c) == "pass" for c in CONTROL)),
        ("OLD exits 1", old_rc == 1),
    ]
    print("== old-vs-fix verdict ==")
    for text, ok in checks:
        print(f"  {text}: {'yes' if ok else 'NO'}")
    ok = all(ok for _, ok in checks)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
