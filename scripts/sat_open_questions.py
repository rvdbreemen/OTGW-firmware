#!/usr/bin/env python3
"""Print or refresh the Live queue of docs/sat/open-questions.md (TASK-1629).

The question table in docs/sat/open-questions.md is the record. The "Live queue" list at
the top of that file is derived from it: every row whose Status starts with asked or
queued and that has no answering entry (no checkmark in the Answered column).

    python scripts/sat_open_questions.py            # print the open rows
    python scripts/sat_open_questions.py --update   # rewrite the Live queue block in place
    python scripts/sat_open_questions.py --check    # exit 1 when the block is stale

Run --update after you add, ask, answer or drop a question in the table.
tests/test_open_questions_status.py fails when the block is stale.
"""
import re
import sys
from pathlib import Path

DOC = Path(__file__).resolve().parent.parent / "docs" / "sat" / "open-questions.md"
ROW = re.compile(r"^\| *((?:Q|Conf|QD)[\w.-]*)[^|]*\|")
BEGIN = "<!-- live-queue:begin (generated by scripts/sat_open_questions.py --update) -->"
END = "<!-- live-queue:end -->"


def rows(text):
    """Yield (id, answered, status, topic) for every question row of the table."""
    for line in text.splitlines():
        m = ROW.match(line)
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4:
            yield m.group(1), cells[1], cells[2], cells[3]


def open_rows(text):
    return [r for r in rows(text)
            if re.match(r"(asked|queued)\b", r[2], re.I) and not r[1].startswith("✓")]


def render(text):
    lines = []
    for qid, ans, status, topic in open_rows(text):
        state = "asked" if status.lower().startswith("asked") else "queued"
        partial = f", partial answer {ans}" if ans.startswith("?") else ""
        lines.append(f"- **{qid}** ({state}{partial}): {topic}")
    return "\n".join(lines) if lines else "- none"


def block(text):
    """Return (start, end) offsets of the generated list between the markers, or None."""
    b, e = text.find(BEGIN), text.find(END)
    if b == -1 or e == -1 or e < b:
        return None
    return b + len(BEGIN), e


def main(argv):
    raw = DOC.read_bytes().decode("utf-8")
    nl = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    want = "\n" + render(text) + "\n"
    span = block(text)
    if "--update" in argv or "--check" in argv:
        if span is None:
            print(f"markers not found in {DOC}", file=sys.stderr)
            return 2
        have = text[span[0]:span[1]]
        if "--check" in argv:
            if have != want:
                print("Live queue is stale: run python scripts/sat_open_questions.py --update", file=sys.stderr)
                return 1
            print("Live queue is current")
            return 0
        new = text[:span[0]] + want + text[span[1]:]
        DOC.write_bytes(new.replace("\n", nl).encode("utf-8"))
        print(f"Live queue updated: {len(open_rows(text))} open rows")
        return 0
    print(render(text))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
