#!/usr/bin/env python3
"""TASK-1696: write src/OTGW-firmware/faviconData.h from src/OTGW-firmware/data/favicon.ico.

The firmware serves /favicon.ico from app flash (FSexplorer.ino, webSendFlashBody), so a browser's
favicon request opens no LittleFS file and takes no web file-gate slot. The header is checked in;
rerun this script after changing the icon. tests/test_favicon_flash.py fails when the header and the
file differ.

Run: python scripts/gen_favicon_header.py
"""
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src" / "OTGW-firmware" / "data" / "favicon.ico"
OUT = REPO / "src" / "OTGW-firmware" / "faviconData.h"


def render(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 16):
        rows.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return (
        "// GENERATED by scripts/gen_favicon_header.py from data/favicon.ico (TASK-1696). Do not edit.\n"
        "// /favicon.ico is served from app flash: no LittleFS open, no web file-gate slot.\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "#include <pgmspace.h>\n\n"
        "static const uint8_t FAVICON_ICO[] PROGMEM = {\n" + "\n".join(rows) + "\n};\n"
        "static const size_t FAVICON_ICO_LEN = sizeof(FAVICON_ICO);\n"
    )


def main() -> None:
    data = SRC.read_bytes()
    OUT.write_text(render(data), encoding="ascii", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
