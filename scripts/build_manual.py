#!/usr/bin/env python3
"""Build docs/MANUAL.md from the English manual chapters (TASK-2030).

docs/MANUAL.md is the single-file English manual. It used to be kept by hand next to the chapter files in
docs/manuals/en/ and drifted from them. It is now generated: a fixed header, then ch01..ch10 in order,
separated by a horizontal rule. Relative links in a chapter point from docs/manuals/en/; they are rewritten
to point from docs/ so they still resolve in MANUAL.md.

Edit the chapters, never MANUAL.md, then run:
  python scripts/build_manual.py          # rewrite docs/MANUAL.md
  python scripts/build_manual.py --check  # exit 1 when docs/MANUAL.md is not the generated text
"""
import argparse
import posixpath
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CHAPTER_DIR = "docs/manuals/en"
OUT = REPO / "docs" / "MANUAL.md"

HEADER = """# OTGW-firmware 2.0.0 Manual

<!-- Generated by scripts/build_manual.py from docs/manuals/en/ch*.md (TASK-2030). Edit the chapters, not this file. -->

This manual covers the full OTGW-firmware v2.0.0 product for both end users (Chapters 1-7) and developers (Chapters 8-10). Individual chapters are also available as separate files in `docs/manuals/en/` (English) and `docs/manuals/nl/` (Dutch).
"""

LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def chapters():
    files = sorted((REPO / CHAPTER_DIR).glob("ch[0-9][0-9]-*.md"))
    if not files:
        raise SystemExit(f"no chapters in {CHAPTER_DIR}")
    return files


def rebase_link(target: str) -> str:
    """A link relative to docs/manuals/en/ becomes relative to docs/; absolute and anchor links stay."""
    if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith(("#", "/")):
        return target
    path, sep, frag = target.partition("#")
    if not path:
        return target
    resolved = posixpath.normpath(posixpath.join(CHAPTER_DIR, path))
    return posixpath.relpath(resolved, "docs") + sep + frag


def build() -> str:
    parts = [HEADER.rstrip("\n")]
    for f in chapters():
        text = f.read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")
        text = LINK.sub(lambda m: m.group(1) + rebase_link(m.group(2)) + m.group(3), text)
        parts.append(text)
    return "\n\n---\n\n".join(parts) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only compare, do not write")
    args = ap.parse_args()
    want = build()
    have = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
    if args.check:
        if have != want:
            print("docs/MANUAL.md is not the generated text: run python scripts/build_manual.py", file=sys.stderr)
            return 1
        print("docs/MANUAL.md matches the chapters")
        return 0
    OUT.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)} ({want.count(chr(10))} lines from {len(chapters())} chapters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
