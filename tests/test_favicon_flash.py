#!/usr/bin/env python3
"""TASK-1696 part B: /favicon.ico comes from app flash, byte for byte the file in data/.

Before, every page load also fetched /favicon.ico through the LittleFS file route (webSendFile), which
opens a file and takes one of the two web file-gate slots (ADR-165) next to the page itself. Now the
route serves FAVICON_ICO from src/OTGW-firmware/faviconData.h (generated by
scripts/gen_favicon_header.py) through webSendFlashBody(), which takes neither gate.

Checked:
  bytes     the header's array is exactly data/favicon.ico (AC3), and its length constant is sizeof;
  route     FSexplorer.ino registers GET /favicon.ico on webSendFlashBody(FAVICON_ICO, FAVICON_ICO_LEN),
            not on webSendFile, with the image/x-icon type the LittleFS route used;
  binary    webSendFlashBody() sends the explicit length (an .ico/.png has zero bytes, so strlen_P
            would cut it) and keeps the ETag / no-cache / 304 rule of the pages.
On the code before TASK-1696 the header and the route do not exist, so the test fails there.

Not covered here: the served bytes on a real device (bench: curl and sha256).
"""
import re
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FW = REPO / "src" / "OTGW-firmware"


class FaviconFromFlash(unittest.TestCase):
    def test_header_bytes_equal_the_file(self):
        hdr = FW / "faviconData.h"
        self.assertTrue(hdr.exists(), "faviconData.h missing (favicon not in flash)")
        text = hdr.read_text(encoding="ascii")
        body = text[text.index("FAVICON_ICO[] PROGMEM = {") :]
        body = body[: body.index("};")]
        got = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-fA-F]{2})", body))
        want = (FW / "data" / "favicon.ico").read_bytes()
        self.assertEqual(len(got), len(want))
        self.assertEqual(got, want, "faviconData.h is stale: rerun scripts/gen_favicon_header.py")
        self.assertIn("FAVICON_ICO_LEN = sizeof(FAVICON_ICO)", text)

    def test_route_uses_flash_not_the_file_gate(self):
        src = (FW / "FSexplorer.ino").read_text(encoding="utf-8")
        self.assertIn('#include "faviconData.h"', src)
        routes = [l for l in src.splitlines() if 'server.on("/favicon.ico"' in l]
        self.assertEqual(len(routes), 1, routes)
        r = routes[0]
        self.assertIn("webSendFlashBody(", r)
        self.assertIn("FAVICON_ICO, FAVICON_ICO_LEN", r)
        self.assertIn('PSTR("image/x-icon")', r)
        self.assertNotIn("webSendFile", r)

    def test_flash_body_sends_the_explicit_length(self):
        compat = (FW / "webServerCompat.h").read_text(encoding="utf-8")
        start = compat.index("inline void webSendFlashBody(")
        fn = compat[start : compat.index("\n}\n", start)]
        self.assertIn("beginResponse(200, String(FPSTR(contentType)), body, len)", fn)
        self.assertNotIn("strlen", fn)
        self.assertIn("webSendStatus(304)", fn)
        self.assertIn('F("no-cache")', fn)
        self.assertNotIn("webFileGate", fn)


if __name__ == "__main__":
    unittest.main(verbosity=2)
