#!/usr/bin/env python3
"""TASK-1955 (ADR-247): the settings help is stored gzipped in app flash and served as is.

/settings-help.json was a 17.8 KB raw string in flash (ADR-194); it is now a gzip byte array (settingsHelpGz.h,
generated by scripts/webui_pages.py from the readable JSON in settingsHelp.h) sent with Content-Encoding: gzip.

Checks, on the real files:
1. settingsHelpGz.h gunzips to exactly the JSON body of settingsHelp.h, which parses as JSON;
2. the committed generated headers (settingsHelpGz.h, otgwSimulationFixtureZ.h) equal what the generator writes now,
   so a JSON or fixture edit without a regenerate is caught;
3. the route serves SETTINGS_HELP_GZ through serveProgmemAsset() -> webSendFlashBody(..., gzip=true) with the
   "/settings-help.json" ETag path, and settingsHelp.h itself is no longer compiled into the image;
4. build.py and the PlatformIO pre-script both run the generator.
Red on the code before TASK-1955 (no settingsHelpGz.h). Run: python tests/test_progmem_assets_deflated.py
"""
import gzip
import json
import re
import sys
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FW = REPO / "src" / "OTGW-firmware"
sys.path.insert(0, str(REPO / "scripts"))


def text(p):
    return p.read_text(encoding="utf-8").replace("\r\n", "\n")


def array_bytes(src, symbol):
    m = re.search(symbol + r"\[\]\s*PROGMEM\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise AssertionError(symbol + " not found")
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", m.group(1)))


class SettingsHelpGzipped(unittest.TestCase):
    def test_1_gunzip_equals_the_readable_json(self):
        import webui_pages
        gz = array_bytes(text(FW / "settingsHelpGz.h"), "SETTINGS_HELP_GZ")
        body = gzip.decompress(gz)
        self.assertEqual(body, webui_pages.settings_help_json(FW))
        doc = json.loads(body)
        self.assertGreater(len(doc), 100, "the help document lost its keys")
        self.assertLess(len(gz), len(body) // 2, "the help is not really compressed")

    def test_2_committed_headers_match_the_generator(self):
        import webui_pages
        for name, want in webui_pages.asset_headers(REPO).items():
            self.assertEqual(text(FW / name), want, name + " is stale: run the build (or webui_pages.write_asset_headers)")

    def test_3_route_sends_the_gzip_array(self):
        fs = text(FW / "FSexplorer.ino")
        self.assertIn('#include "settingsHelpGz.h"', fs)
        self.assertNotIn('#include "settingsHelp.h"', fs, "the readable source must not be compiled in as well")
        self.assertRegex(fs, r'serveProgmemAsset\("/settings-help\.json", PSTR\("application/json"\), SETTINGS_HELP_GZ, '
                             r'SETTINGS_HELP_GZ_LEN\)')
        m = re.search(r"static void serveProgmemAsset\([^)]*\)\s*\{(.*?)\n\}", fs, re.S)
        self.assertIsNotNone(m)
        self.assertIn("webSendFlashBody(mime, gzBody, gzLen, path, true)", m.group(1))
        for name in ("settingsHelp.h",):
            hits = [p.name for p in FW.glob("*.ino") if '#include "%s"' % name in text(p)]
            self.assertEqual(hits, [], name + " is included by " + ", ".join(hits))

    def test_4_both_build_paths_run_the_generator(self):
        self.assertIn("webui_pages.write_asset_headers(project_dir)", text(REPO / "build.py"))
        self.assertIn("webui_pages.write_asset_headers(_project)", text(REPO / "scripts" / "platformio_webui.py"))


if __name__ == "__main__":
    unittest.main(verbosity=2)
